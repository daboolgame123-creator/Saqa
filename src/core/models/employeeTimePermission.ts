/**
 * EmployeeTimePermission — نموذج الزمنية (الخروج/العودة خلال يوم الدوام)
 * (PHASE 1 — نماذج شؤون المنتسبين · Phase 18: المدة بالدقائق)
 *
 * القرارات المعمارية المعتمدة:
 * - الخيار A: نموذج مستقل مرتبط بموظف واحد عبر employeeId.
 * - transactionId?: علاقة اختيارية أحادية الاتجاه مع Transaction — لا حقول عكسية.
 * - **المدة بالدقائق تُخزَّن ولا تُشتق**: `durationMinutes` هي الحقيقة الوحيدة
 *   للمدة (الخطة §7.11 و§14.3)، ويحسبها محرك الدقائق على الخادم من
 *   `timeOut`/`timeIn` ويخزّنها. لا تُشتق مرتين (مرة في النموذج ومرة في
 *   المستودع) — لهذا الحقل هنا وفي عقد المستودع والـDTO، لا في مكان ثالث.
 * - التاريخ والوقت حقول منفصلة: تاريخ YYYY-MM-DD، وقت HH:mm بنظام 24 ساعة.
 */

/** الحالة الإجرائية للزمنية */
export type TimePermissionStatus =
  | 'registered'   // مسجلة
  | 'approved'     // معتمدة
  | 'cancelled';   // ملغاة

export interface EmployeeTimePermission {
  /** معرف السجل الفريد */
  id: string;
  /** الرابط الأساسي مع Employee.id — موظف واحد لكل سجل */
  employeeId: string;
  /** تاريخ الزمنية — YYYY-MM-DD */
  date: string;
  /** وقت الخروج — HH:mm بنظام 24 ساعة */
  timeOut: string;
  /** وقت العودة إن وُجد — HH:mm (يبقى undefined إن لم يُسجل) */
  timeIn?: string;
  /**
   * المدة بالدقائق — §14.3.
   *
   * غائبة فقط إذا لم يُسجَّل وقت العودة بعد (السجل غير مكتمل)، فليس هناك
   * ما يُحوَّل. وتجاوز منتصف الليل سياسة لم تحسمها الخطة، فلا تُخترع هنا:
   * الزمنية التي يعود فيها الوقت قبل وقت الخروج لا تُشتق لها مدة وتبقى
   * `undefined` حتى تُحسم القاعدة.
   */
  durationMinutes?: number;
  /** سبب الخروج */
  reason?: string;
  /** الحالة الإجرائية */
  status: TimePermissionStatus;
  /** ربط اختياري أحادي الاتجاه بمعاملة الكتاب الرسمي (Transaction.id) */
  transactionId?: string;
  notes?: string;
}
